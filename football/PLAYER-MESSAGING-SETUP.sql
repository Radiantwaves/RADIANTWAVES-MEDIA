-- RadiantWaves Football Talent: secure in-app player messaging
-- Run once in Supabase SQL Editor.
create table if not exists public.player_messages (
  id bigint generated by default as identity primary key,
  player_user_id uuid not null references auth.users(id) on delete cascade,
  sender_user_id uuid not null references auth.users(id) on delete cascade,
  sender_role text not null check (sender_role in ('admin','player')),
  subject text not null check (char_length(subject) between 1 and 180),
  body text not null check (char_length(body) between 1 and 10000),
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists player_messages_player_created_idx
  on public.player_messages (player_user_id, created_at desc);

alter table public.player_messages enable row level security;

drop policy if exists "Players and admins can read message threads" on public.player_messages;
create policy "Players and admins can read message threads"
on public.player_messages for select to authenticated
using (
  player_user_id = (select auth.uid())
  or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
);

drop policy if exists "Admins and players can send messages" on public.player_messages;
create policy "Admins and players can send messages"
on public.player_messages for insert to authenticated
with check (
  sender_user_id = (select auth.uid())
  and (
    (
      sender_role = 'admin'
      and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
    )
    or
    (
      sender_role = 'player'
      and player_user_id = (select auth.uid())
    )
  )
);

drop policy if exists "Recipients can mark messages as read" on public.player_messages;
create policy "Recipients can mark messages as read"
on public.player_messages for update to authenticated
using (
  player_user_id = (select auth.uid())
  or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
)
with check (
  player_user_id = (select auth.uid())
  or (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
);

grant select, insert on public.player_messages to authenticated;
revoke update on public.player_messages from authenticated;
grant update (read_at) on public.player_messages to authenticated;
grant usage, select on sequence public.player_messages_id_seq to authenticated;
